// -------------------------------------------------------------
//  Product Import CLI
//  - Standalone script (connects to MongoDB directly, does not
//    need the API server running)
//  - Accepts a JSON or CSV file of products, maps/normalizes them
//    onto the Product schema, and upserts them (create-or-update,
//    keyed on source+sourceId — same logic the Basalam/Technolife
//    ingestion services use, see product.service.js).
//  - One bad row never aborts the whole import; every row is
//    tried, and a full report is printed + saved at the end.
//
//  Usage:
//    npm run import:products -- --file ./products.json --source manual
//    npm run import:products -- --file ./products.csv --format csv --source manual
//
//  Expected input shape (JSON array or CSV columns) — matches the
//  Product schema fields directly (see models/product.model.js).
//  Only title, price, source, sourceId are required; everything
//  else is optional and normalized/defaulted below.
//
//    title, slug, description, brand, category, subcategory,
//    price, originalPrice, discount, stock, availability,
//    image, images (CSV: pipe-separated), specs (JSON string),
//    specifications (JSON string), attributes (JSON string),
//    tags (CSV: pipe-separated), source, sourceId, url
// -------------------------------------------------------------

import fs from "fs/promises";
import path from "path";
import mongoose from "mongoose";
import { parse as parseCsv } from "csv-parse/sync";
import dotenv from "dotenv";

import Product from "../models/product.model.js";
import Category from "../models/category.model.js";
import logger from "../utils/logger.js";

dotenv.config({ path: process.env.NODE_ENV === "production" ? ".env.production" : ".env.development" });
dotenv.config();

// -------------------------------------------------------------
//  CLI argument parsing (no extra dependency — simple --key value)
// -------------------------------------------------------------
function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) {
      const key = argv[i].slice(2);
      const value = argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[++i] : true;
      args[key] = value;
    }
  }
  return args;
}

function tryParseJson(value, fallback) {
  if (!value) return fallback;
  if (typeof value === "object") return value;
  try {
    return JSON.parse(value);
  } catch {
    return fallback;
  }
}

function splitList(value) {
  if (Array.isArray(value)) return value;
  if (!value) return [];
  return String(value)
    .split("|")
    .map((v) => v.trim())
    .filter(Boolean);
}

/**
 * Normalizes one raw row (from JSON or CSV) into a Product-shaped
 * object. Doesn't touch the database — pure transformation, so
 * it's easy to unit-test independently later.
 */
function normalizeRow(row, defaultSource) {
  const source = row.source || defaultSource;
  const sourceId = row.sourceId != null ? String(row.sourceId) : undefined;

  return {
    title: row.title?.toString().trim(),
    slug: row.slug?.toString().trim() || undefined, // auto-generated by the model if omitted
    description: row.description?.toString().trim(),
    brand: row.brand?.toString().trim(),
    category: row.category?.toString().trim(),
    price: row.price != null ? Number(row.price) : undefined,
    originalPrice: row.originalPrice != null ? Number(row.originalPrice) : undefined,
    discount: row.discount != null ? Number(row.discount) : 0,
    stock: row.stock != null ? Number(row.stock) : null,
    availability: row.availability || "unknown",
    image: row.image?.toString().trim(),
    images: splitList(row.images),
    specs: tryParseJson(row.specs, {}),
    specifications: tryParseJson(row.specifications, {}),
    attributes: tryParseJson(row.attributes, {}),
    tags: splitList(row.tags),
    source,
    sourceId,
    url: row.url?.toString().trim(),
    searchableText: [row.title, row.brand, row.category].filter(Boolean).join(" "),
  };
}

function validateRow(mapped) {
  const errors = [];
  if (!mapped.title) errors.push("title الزامی است");
  if (!mapped.price || Number.isNaN(mapped.price)) errors.push("price نامعتبر است");
  if (!mapped.source) errors.push("source الزامی است");
  if (!mapped.sourceId) errors.push("sourceId الزامی است");
  return errors;
}

/**
 * Best-effort category mapping: if `category` matches an existing
 * Category by name or slug, we don't create a new one. Unknown
 * categories are left as free text on the product (category is a
 * String field, not a hard foreign key) so import never blocks on
 * missing category setup — but they're flagged in the report so
 * you know which ones need a real Category document.
 */
async function checkCategoryMapping(categoryName, unmappedSet) {
  if (!categoryName) return;
  const exists = await Category.findOne({
    $or: [{ name: categoryName }, { slug: categoryName }],
  }).lean();
  if (!exists) unmappedSet.add(categoryName);
}

async function readRows(filePath, format) {
  const raw = await fs.readFile(filePath, "utf-8");

  if (format === "csv") {
    return parseCsv(raw, { columns: true, skip_empty_lines: true, trim: true });
  }

  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed)) {
    throw new Error("فایل JSON باید یک آرایه از محصولات باشد");
  }
  return parsed;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));

  if (!args.file) {
    console.error("استفاده: npm run import:products -- --file <path> [--format json|csv] [--source manual]");
    process.exit(1);
  }

  const filePath = path.resolve(process.cwd(), args.file);
  const format = args.format || (filePath.endsWith(".csv") ? "csv" : "json");
  const defaultSource = args.source || "manual";

  const report = {
    total: 0,
    imported: 0,
    updated: 0,
    skipped: 0,
    duplicated: 0,
    invalid: 0,
    errors: [],
    unmappedCategories: [],
  };

  await mongoose.connect(process.env.MONGO_URI || "mongodb://127.0.0.1:27017/mira");
  logger.info("Import: connected to MongoDB");

  const rows = await readRows(filePath, format);
  const unmappedCategories = new Set();

  for (const row of rows) {
    report.total += 1;

    try {
      const mapped = normalizeRow(row, defaultSource);
      const errors = validateRow(mapped);

      if (errors.length > 0) {
        report.invalid += 1;
        report.errors.push({ row: report.total, sourceId: mapped.sourceId, errors });
        continue;
      }

      await checkCategoryMapping(mapped.category, unmappedCategories);

      const existing = await Product.findOne({ source: mapped.source, sourceId: mapped.sourceId });

      if (existing) {
        await Product.updateOne({ _id: existing._id }, { $set: mapped });
        report.updated += 1;
      } else {
        await Product.create(mapped);
        report.imported += 1;
      }
    } catch (err) {
      report.invalid += 1;
      report.errors.push({ row: report.total, error: err.message });
    }
  }

  report.unmappedCategories = [...unmappedCategories];

  console.log("\n=== گزارش Import محصولات ===");
  console.log(`Total:       ${report.total}`);
  console.log(`Imported:    ${report.imported}`);
  console.log(`Updated:     ${report.updated}`);
  console.log(`Skipped:     ${report.skipped}`);
  console.log(`Duplicated:  ${report.duplicated}`);
  console.log(`Invalid:     ${report.invalid}`);
  if (report.unmappedCategories.length) {
    console.log(`Unmapped categories (نیاز به ساخت Category دارند): ${report.unmappedCategories.join(", ")}`);
  }
  if (report.errors.length) {
    console.log(`\nErrors (${report.errors.length}):`);
    for (const e of report.errors.slice(0, 50)) {
      console.log(" -", JSON.stringify(e));
    }
    if (report.errors.length > 50) {
      console.log(`   ...و ${report.errors.length - 50} خطای دیگر`);
    }
  }

  const logsDir = path.resolve(process.cwd(), "logs");
  await fs.mkdir(logsDir, { recursive: true });
  const reportPath = path.join(logsDir, `import-report-${Date.now()}.json`);
  await fs.writeFile(reportPath, JSON.stringify(report, null, 2));
  console.log(`\nگزارش کامل ذخیره شد: ${reportPath}`);

  await mongoose.disconnect();
  process.exit(report.invalid > 0 ? 1 : 0);
}

main().catch((err) => {
  console.error("Import failed:", err.message);
  process.exit(1);
});
